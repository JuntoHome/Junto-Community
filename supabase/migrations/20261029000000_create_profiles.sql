-- "Who Can Help?" profiles (CMS-09): one row per organization. Admins write them in
-- /admin; the public site shows a profile only once it is published
-- (docs/JCA_CMS_Plan.md sections 6 and 7). Run after 20261028000000_create_admins.sql.

create table if not exists public.profiles (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 1 and 200),
  -- The page address, /<overview>/<slug>: lowercase words joined by hyphens.
  slug text not null check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 100),
  tagline text check (char_length(tagline) <= 300),
  intro text check (char_length(intro) <= 20000),
  how_they_help text check (char_length(how_they_help) <= 20000),
  who_should_explore text check (char_length(who_should_explore) <= 20000),
  history text check (char_length(history) <= 20000),
  contact_name text check (char_length(contact_name) <= 200),
  contact_role text check (char_length(contact_role) <= 200),
  contact_email text check (contact_email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' and char_length(contact_email) <= 254),
  contact_phone text check (char_length(contact_phone) <= 50),
  website_url text check (website_url ~ '^https?://' and char_length(website_url) <= 2000),
  logo_path text check (char_length(logo_path) <= 500),
  status text not null default 'draft' check (status in ('draft', 'published')),
  -- New profiles go to the end of the list; reordering sets the numbers directly.
  display_order integer generated by default as identity,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.admins (user_id) on delete set null,
  -- Set instead of deleting the row, so a deleted profile can be restored.
  deleted_at timestamptz,
  -- Drafts may be incomplete. A published profile must have everything its public page needs.
  constraint profiles_published_complete check (
    status = 'draft' or (
      coalesce(btrim(tagline), '') <> ''
      and coalesce(btrim(intro), '') <> ''
      and coalesce(btrim(how_they_help), '') <> ''
      and coalesce(btrim(who_should_explore), '') <> ''
      and website_url is not null
    )
  )
);

-- Two live profiles can't share an address. A deleted profile's address can be reused.
create unique index if not exists profiles_slug_key on public.profiles (slug) where deleted_at is null;

-- Record when a profile was last changed and by which admin, whatever the app sends.
create or replace function private.stamp_profile_edit()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  new.updated_by := coalesce(auth.uid(), new.updated_by);
  if tg_op = 'UPDATE' then
    new.created_at := old.created_at;
  end if;
  return new;
end;
$$;

revoke execute on function private.stamp_profile_edit() from public, anon, authenticated;

drop trigger if exists profiles_stamp_edit on public.profiles;
create trigger profiles_stamp_edit
  before insert or update on public.profiles
  for each row execute function private.stamp_profile_edit();

alter table public.profiles enable row level security;

-- Set the grants explicitly (Supabase stops granting new tables by default on Oct 30, 2026).
-- No delete for anyone through the API: deleting a profile means setting deleted_at.
revoke all on public.profiles from anon, authenticated;
grant select on public.profiles to anon, authenticated;
grant insert, update on public.profiles to authenticated;
grant select, insert, update, delete on public.profiles to service_role;

-- Visitors, and logged-in people who aren't admins, see published profiles only.
drop policy if exists "Anyone can read published profiles" on public.profiles;
create policy "Anyone can read published profiles" on public.profiles
  for select to anon, authenticated
  using (status = 'published' and deleted_at is null);

drop policy if exists "Admins can read all profiles" on public.profiles;
create policy "Admins can read all profiles" on public.profiles
  for select to authenticated
  using ((select private.is_admin()));

drop policy if exists "Admins can add profiles" on public.profiles;
create policy "Admins can add profiles" on public.profiles
  for insert to authenticated
  with check ((select private.is_admin()));

drop policy if exists "Admins can edit profiles" on public.profiles;
create policy "Admins can edit profiles" on public.profiles
  for update to authenticated
  using ((select private.is_admin()))
  with check ((select private.is_admin()));
